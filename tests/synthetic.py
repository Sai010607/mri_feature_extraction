"""
Builds tiny but structurally realistic FreeSurfer subject directories for tests.

Each subject gets mri/{aseg,aparc+aseg,norm}.mgz and stats/{aseg,lh.aparc,rh.aparc}.stats.
The .stats numbers are computed from the volumes themselves, so the stats-table
feature family and the voxel-level feature family must agree.
"""

from __future__ import annotations

from pathlib import Path
from typing import Optional

import nibabel as nib
import numpy as np

from fs_pipeline import config

SHAPE = (24, 24, 24)
ZOOMS = (1.0, 1.0, 2.0)  # anisotropic on purpose: catches voxel-volume bugs
AFFINE = np.array([
    [-1.0, 0.0, 0.0, 12.0],
    [0.0, 0.0, 2.0, -24.0],   # FreeSurfer conformed-style axis permutation
    [0.0, -1.0, 0.0, 12.0],
    [0.0, 0.0, 0.0, 1.0],
])

#: canonical ROI -> raw StructName used in the .stats files (modern naming)
ASEG_STRUCT_NAMES = {
    "Left_Hippocampus": "Left-Hippocampus", "Right_Hippocampus": "Right-Hippocampus",
    "Left_Amygdala": "Left-Amygdala", "Right_Amygdala": "Right-Amygdala",
    "Left_Putamen": "Left-Putamen", "Right_Putamen": "Right-Putamen",
    "Left_Thalamus_Proper": "Left-Thalamus", "Right_Thalamus_Proper": "Right-Thalamus",
    "Brain_Stem": "Brain-Stem",
    "Left_Lateral_Ventricle": "Left-Lateral-Ventricle", "Right_Lateral_Ventricle": "Right-Lateral-Ventricle",
    "Third_Ventricle": "3rd-Ventricle",
    "CC_Posterior": "CC_Posterior", "CC_Mid_Posterior": "CC_Mid_Posterior", "CC_Central": "CC_Central",
    "CC_Mid_Anterior": "CC_Mid_Anterior", "CC_Anterior": "CC_Anterior",
    "Left_Cerebellum_Cortex": "Left-Cerebellum-Cortex", "Right_Cerebellum_Cortex": "Right-Cerebellum-Cortex",
}


def _label_volumes(seed: int):
    """Place a distinct 2x2x2 block for every ROI so each is non-empty and non-overlapping."""
    aseg = np.zeros(SHAPE, dtype=np.uint8)
    aparc = np.zeros(SHAPE, dtype=np.int32)
    rng = np.random.default_rng(seed)
    corners = [(x, y, z) for x in range(0, 22, 4) for y in range(0, 22, 4) for z in range(0, 22, 8)]
    for i, name in enumerate(config.ALL_ROI_NAMES):
        x, y, z = corners[i]
        size = int(rng.integers(2, 4))
        block = (slice(x, x + size), slice(y, y + size), slice(z, z + size))
        if name in config.ASEG_SEGIDS:
            aseg[block] = config.ASEG_SEGIDS[name]
        else:
            aparc[block] = config.APARC_SEGIDS[name]
    # aparc+aseg also contains the subcortical labels in real data
    aparc = np.where(aseg > 0, aseg.astype(np.int32), aparc)
    return aseg, aparc


def make_subject(
    root: Path,
    group: str,
    subject_id: str,
    seed: int = 0,
    legacy_stats: bool = False,
    write_stats: bool = True,
    write_volumes: bool = True,
    drop_aseg_rows: Optional[set] = None,
    wrong_intensity_shape: bool = False,
) -> Path:
    subj = root / group / subject_id
    (subj / "mri").mkdir(parents=True, exist_ok=True)
    (subj / "stats").mkdir(parents=True, exist_ok=True)

    aseg, aparc = _label_volumes(seed)
    rng = np.random.default_rng(1000 + seed)
    norm = rng.normal(100.0, 15.0, size=SHAPE).astype(np.float32)
    if wrong_intensity_shape:
        norm = norm[:-2]

    if write_volumes:
        def save(arr, name):
            img = nib.MGHImage(arr, AFFINE)
            img.header.set_zooms(ZOOMS)
            nib.save(img, str(subj / "mri" / name))
        save(aseg, "aseg.mgz")
        save(aparc, "aparc+aseg.mgz")
        save(norm, "norm.mgz")

    if write_stats:
        _write_aseg_stats(subj / "stats" / "aseg.stats", aseg, norm, legacy_stats, drop_aseg_rows or set())
        for hemi in ("lh", "rh"):
            _write_aparc_stats(subj / "stats" / f"{hemi}.aparc.stats", legacy_stats)
    return subj


def _write_aseg_stats(path: Path, aseg, norm, legacy: bool, drop: set) -> None:
    cols = ["Index", "SegId", "NVoxels", "Volume_mm3", "StructName",
            "normMean", "normStdDev", "normMin", "normMax", "normRange"]
    lines = ["# Title Segmentation Statistics", "# generated by synthetic test fixture",
             "# Measure BrainSeg, BrainSegVol, Brain Segmentation Volume, 1000000.0, mm^3"]
    if legacy:
        lines += [f"# TableCol {i + 1:2d} ColHeader {c}" for i, c in enumerate(cols)]
    else:
        lines.append("# ColHeaders  " + " ".join(cols))
    voxel_vol = ZOOMS[0] * ZOOMS[1] * ZOOMS[2]
    for i, (roi, struct) in enumerate(ASEG_STRUCT_NAMES.items(), start=1):
        if roi in drop:
            continue
        m = aseg == config.ASEG_SEGIDS[roi]
        vals = norm[m].astype(np.float64) if norm.shape == aseg.shape else np.array([0.0])
        n = int(m.sum())
        lines.append(
            f"{i:3d} {config.ASEG_SEGIDS[roi]:4d} {n:6d} {n * voxel_vol:10.1f}  {struct:<28s} "
            f"{vals.mean():8.4f} {vals.std():8.4f} {vals.min():8.4f} {vals.max():8.4f} {vals.max() - vals.min():8.4f}"
        )
    path.write_text("\n".join(lines) + "\n")


def _write_aparc_stats(path: Path, legacy: bool) -> None:
    cols = ["StructName", "NumVert", "SurfArea", "GrayVol", "ThickAvg", "ThickStd",
            "MeanCurv", "GausCurv", "FoldInd", "CurvInd"]
    lines = ["# Table of FreeSurfer cortical parcellation anatomical statistics",
             "# Measure Cortex, NumVert, Number of Vertices, 100000, unitless"]
    if legacy:
        lines += [f"# TableCol {i + 1:2d} ColHeader {c}" for i, c in enumerate(cols)]
    else:
        lines.append("# ColHeaders " + " ".join(cols))
    lines += [
        "bankssts            1000    700    1800  2.500 0.400     0.100     0.020       10     1.0",
        "entorhinal           500    300    1100  3.100 0.600     0.120     0.030        5     0.7",
        "insula              2000   1400    4000  2.900 0.500     0.090     0.020       30     2.1",
    ]
    path.write_text("\n".join(lines) + "\n")
